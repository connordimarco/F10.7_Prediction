#!/usr/bin/env python3
"""Aggregate all cells' scorecards -> LEADERBOARD.md (generated, don't edit)."""

import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MATRIX = os.path.normpath(os.path.join(HERE, ".."))


def table(cards, title):
    lines = [
        title,
        "",
        f"Test origins: {cards[0]['n_origins']} ({cards[0]['test_span'][0]} -> "
        f"{cards[0]['test_span'][1]}), observed F10.7, sorted by pooled RMSE.",
        "",
        "| cell | RMSE | MAE | r | skill | L1-7 | L8-14 | L15-30 | hi-act RMSE |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for c in cards:
        p, b = c["pooled"], c["bands"]
        hi = f"{c['high_activity_rmse']:.2f}" if c.get("high_activity_rmse") else "-"
        lines.append(
            f"| {c['cell']} | {p['rmse']:.2f} | {p['mae']:.2f} | {p['r']:.3f} "
            f"| {p['skill_vs_persist']:+.3f} | {b['L1_7']['skill_vs_persist']:+.3f} "
            f"| {b['L8_14']['skill_vs_persist']:+.3f} "
            f"| {b['L15_30']['skill_vs_persist']:+.3f} | {hi} |"
        )
    return lines


def main():
    sys.path.insert(0, HERE)
    import common

    cards = []
    for p in sorted(glob.glob(os.path.join(MATRIX, "*", "out", "scorecard.json"))):
        with open(p) as f:
            cards.append(json.load(f))
    cards.sort(key=lambda c: c["pooled"]["rmse"])
    cur = [c for c in cards if c.get("data_version") == common.DATA_VERSION]
    old = [c for c in cards if c.get("data_version") != common.DATA_VERSION]
    lines = ["# Horizon-matrix leaderboard (generated by shared/leaderboard.py)", ""]
    if cur:
        lines += table(cur, f"## Current data ({common.DATA_VERSION})") + [""]
    if old:
        lines += table(
            old,
            "## Frozen: v1 data (2026-08; F10.7 dates one day late, flare spikes "
            "in targets) — NOT comparable with the table above",
        )
    out = os.path.join(MATRIX, "LEADERBOARD.md")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
